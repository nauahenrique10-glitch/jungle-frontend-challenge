async function accountScenario(page: Page, value: string) { await page.evaluate(value => localStorage.setItem('kurio:account-scenario', value), value) }
async function api(page: Page, method: string, path: string, data?: unknown) {
 return page.evaluate(async ({ method, path, data }) => {
  const module = '/src/services/http.ts'; const { http } = await import(module)
  try { const response = await http.request({ method, url: path, data, headers: { Authorization: `Bearer ${localStorage.getItem('kurio:auth-token')}` } }); return { status: response.status, data: response.data } }
  catch (error: unknown) { const response = (error as { response: { status: number; data: unknown } }).response; return { status: response?.status, data: response?.data } }
 }, { method, path, data })
}

 panel = await filters(page)
 await panel.getByRole('button', { name: /^Ethereum/ }).click()
 await expect.poll(() => urlParams(page).get('network')).toBe('ethereum')
 expect(urlParams(page).get('category')).toBe('arte-digital')
 await closeFilters(page)
 await ready(page, 0)
 // Ao remover a categoria, a rede sozinha também deve excluir os itens sem rede.

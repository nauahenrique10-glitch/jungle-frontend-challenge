import { test, expect, type Page } from './test-fixture'

const cards = (page: Page) => page.locator('.catalog-results .nft-card:not(.catalog-skeletons .nft-card)')
const isMobile = (page: Page) => page.viewportSize()!.width <= 800
async function ready(page: Page, count = 9) {
 // The browser load event can precede the async MSW/router bootstrap in main.tsx.
 // Wait for the application container before asserting its loaded state.
 await page.locator('.catalog-results').waitFor({ state: 'attached' })
 await expect(page.locator('.catalog-results')).toHaveAttribute('aria-busy', 'false')
 await expect(cards(page)).toHaveCount(count)
}
async function filters(page: Page) {
 if (!isMobile(page)) return page.locator('.catalog-sidebar')
 await page.getByRole('button', { name: 'Abrir filtros', exact: true }).click()
 return page.getByRole('dialog', { name: 'Filtros do catálogo' })
}
async function closeFilters(page: Page) {
 if (isMobile(page)) await page.getByRole('button', { name: 'Ver resultados', exact: true }).click()
}
async function search(page: Page, text: string) {
 if (!isMobile(page) && !await page.locator('.catalog-search-disclosure').getAttribute('open')) {
  const details = page.locator('.catalog-search-disclosure')
  if (!await details.evaluate(node => (node as HTMLDetailsElement).open)) await details.locator('summary').click()
 }
 const input = page.locator('input[aria-label="Buscar NFTs"]:visible')
 await input.fill(text)
 await input.press('Enter')
}
async function scenario(page: Page, value: string) {
 await page.addInitScript(value => { if (!localStorage.getItem('kurio:catalog-scenario')) localStorage.setItem('kurio:catalog-scenario', value) }, value)
}
const urlParams = (page: Page) => new URL(page.url()).searchParams

test('carrega via REST/MSW com skeleton dimensional e movimento reduzido', async ({ page }) => {
 await scenario(page, 'latency')
 const responsePromise = page.waitForResponse(response => response.url().includes('/api/nfts?'))
 await page.goto('/')
 const skeleton = page.locator('.catalog-skeletons .nft-card').first()
 await expect(skeleton).toBeVisible()
 const skeletonBox = await skeleton.boundingBox()
 await expect(page.getByRole('status')).toHaveText('Carregando catálogo…')
 await page.emulateMedia({ reducedMotion: 'reduce' })
 await expect(page.locator('.catalog-shimmer').first()).toHaveCSS('animation-name', 'none')
 const response = await responsePromise
 expect(response.fromServiceWorker()).toBe(true)
 const body = await response.json()
 expect(body.items).toHaveLength(9)
 expect(body.items.every((item: { id: string; category: unknown; network: unknown; priceEth: unknown }) => item.category === null && item.network === (item.id === 'emerald-ape-042' ? 'ethereum' : null) && typeof item.priceEth === 'string')).toBe(true)
 await ready(page)
 const loadedBox = await cards(page).first().boundingBox()
 expect(loadedBox!.width).toBeCloseTo(skeletonBox!.width, 0)
 expect(loadedBox!.height).toBeCloseTo(skeletonBox!.height, 0)
})


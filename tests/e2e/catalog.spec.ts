test('ordenação e paginação reais, preservando dados durante troca de página', async ({ page }) => {
 await scenario(page, 'latency')
 await page.goto('/?pageSize=3')
 await ready(page, 3)
 await page.getByRole('button', { name: 'Página 2', exact: true }).click()
 await expect.poll(() => urlParams(page).get('page')).toBe('2')
 await expect(page.getByRole('status')).toHaveText('Atualizando catálogo…')
 await expect(cards(page).first()).toContainText('Emerald Ape #042')
 await expect(page.locator('.catalog-skeletons')).toHaveCount(0)
 await ready(page, 3)
 await expect(cards(page).first()).toContainText('Cosmic Bloom #118')
 await page.reload()
 await ready(page, 3)
 await expect(cards(page).first()).toContainText('Cosmic Bloom #118')
 await page.goBack()
 await ready(page, 3)
 expect(urlParams(page).get('page')).toBe('1')
 await page.goForward()
 await ready(page, 3)
 expect(urlParams(page).get('page')).toBe('2')
 const panel = isMobile(page) ? await filters(page) : page.locator('.catalog-toolbar')
 await panel.getByLabel('Ordenar NFTs').selectOption('price-asc')
 await expect.poll(() => urlParams(page).get('page')).toBe('1')
 await closeFilters(page)
 await ready(page, 3)
 await expect(cards(page).first()).toContainText('Golden Signal #160')
 expect(urlParams(page).get('sort')).toBe('price-asc')
 // O tamanho de página também reinicia a paginação e não duplica fixtures.
 await page.getByLabel('Itens por página').selectOption('6')
 await ready(page, 6)
 await page.getByRole('button', { name: 'Próxima página', exact: true }).click()
 await ready(page, 3)
 const ids = await cards(page).evaluateAll(nodes => nodes.map(node => node.getAttribute('data-nft-id')))
 expect(new Set(ids).size).toBe(3)
})


test('erro 500, retry automático limitado e recuperação manual via HTTP', async ({ page }) => {
 await scenario(page, 'error500')
 let attempts = 0
 page.on('response', response => { if (response.url().includes('/api/nfts?')) attempts++ })
 const failedRequest = page.waitForResponse(response => new URL(response.url()).pathname === '/api/nfts' && response.status() === 500 && attempts === 2)
 await page.goto('/')
 const response = await failedRequest
 expect(response.fromServiceWorker()).toBe(true)
 await expect(page.getByRole('alert')).toContainText('Não foi possível carregar o catálogo')
 expect(attempts).toBe(2)
 await expect(cards(page)).toHaveCount(0)
 await page.evaluate(() => localStorage.setItem('kurio:catalog-scenario', 'success'))
 await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
 await ready(page)
 expect(attempts).toBe(3)
})

test('mudanças rápidas não exibem resultado da busca anterior', async ({ page }) => {
 await scenario(page, 'out-of-order')
 await page.goto('/')
 await ready(page)
 const oldRequest = page.waitForRequest(request => request.url().includes('/api/nfts?') && new URL(request.url()).searchParams.get('search') === 'Emerald')
 await search(page, 'Emerald')
 await oldRequest
 await expect(page.locator('.catalog-skeletons')).toBeVisible()
 await search(page, 'Sage')
 await ready(page, 1)
 await expect(cards(page).first()).toContainText('Sage Nomad #009')
 // Aguarda o prazo determinístico da resposta antiga, que deve ser cancelada/descartada.
 await page.waitForTimeout(1400)
 await expect(cards(page)).toHaveCount(1)
 await expect(cards(page).first()).toContainText('Sage Nomad #009')
 expect(urlParams(page).get('search')).toBe('Sage')
})

test('filtros mobile têm foco contido, Escape restaura foco e não há overflow', async ({ page }) => {
 await page.goto('/')
 await ready(page)
 if (isMobile(page)) {
  const opener = page.getByRole('button', { name: 'Abrir filtros', exact: true })
  await opener.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(opener).toBeFocused()
 }
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

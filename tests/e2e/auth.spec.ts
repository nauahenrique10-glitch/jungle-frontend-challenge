test('login válido usa MSW, mantém sessão após refresh e permite logout', async ({ page }) => {
 const responsePromise = page.waitForResponse(response => new URL(response.url()).pathname === '/api/auth/login')
 await login(page)
 const response = await responsePromise
 expect(response.fromServiceWorker()).toBe(true)
 const body = await response.json()
 expect(body.session.user.id).toBe('user-alice')
 expect(body.session.expiresAt).toBeTruthy()
 expect(body.session.user.password).toBeUndefined()
 await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Alice Colecionadora')
 await expect(page.getByRole('button', { name: 'Salvar', exact: true })).toBeDisabled()
 await page.reload()
 await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('alice@kurio.test')
 await page.getByRole('button', { name: 'Sair', exact: true }).click()
 await expect(page.getByRole('form', { name: 'Login', exact: true })).toBeVisible()
 expect(await page.evaluate(() => localStorage.getItem('kurio:auth-token'))).toBeNull()
 await page.goto('/perfil')
 await expect(page.getByRole('form', { name: 'Login', exact: true })).toBeVisible()
})


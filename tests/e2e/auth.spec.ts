test('troca de usuário cancela consulta privada pendente e elimina cache anterior', async ({ page }) => {
 await login(page)
 await page.evaluate(async () => {
  localStorage.setItem('kurio:auth-scenario', 'latency')
  const moduleUrl = '/src/app/query-client.ts'
  const { queryClient } = await import(moduleUrl)
  void queryClient.invalidateQueries({ queryKey: ['private'] })
 })
 await expect(page.locator('.account-content')).toHaveAttribute('aria-busy', 'true')
 await page.getByRole('button', { name: 'Sair', exact: true }).click()
 await expect(page.getByRole('form', { name: 'Login', exact: true })).toBeVisible()
 await expect(page.locator('.account-content')).toHaveCount(0)
 // Aguarda o logout real antes de permitir a próxima autenticação.
 await expect(page.getByRole('form', { name: 'Login' }).getByRole('button', { name: 'Entrar', exact: true })).toBeEnabled()
 await page.evaluate(() => localStorage.setItem('kurio:auth-scenario', 'success'))
 await login(page, 'bruno@kurio.test')
 await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Bruno Colecionador')
 await expect(page.locator('.account-content')).not.toContainText('Alice')
 const privateCache = await page.evaluate(async () => {
  const moduleUrl = '/src/app/query-client.ts'
  const { queryClient } = await import(moduleUrl)
  return queryClient.getQueriesData({ queryKey: ['private'] }).map(([key, value]: [readonly unknown[], unknown]) => ({ key, value }))
 })
 expect(privateCache.length).toBeGreaterThan(0)
 expect(JSON.stringify(privateCache)).not.toContain('user-alice')
 expect(JSON.stringify(privateCache)).not.toContain('alice@kurio.test')
 expect(JSON.stringify(privateCache)).toContain('user-bruno')
 await page.reload()
 await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('bruno@kurio.test')
})

